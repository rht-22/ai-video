"""Shared on-screen title instructions for composition and video verification."""

TITLE_PROMPT = r"""
## 화면 상단 두 줄 제목
완성될 쇼츠에서 가장 흥미로운 사건·행동·반응 하나를 골라 두 줄 제목을 작성하라.

[내용]
- 누가 무엇을 하는지 구체적으로 드러낸다. 전체 줄거리보다 보고 싶어질 순간을 잡는다.
- 작품을 몰라도 이해되게 쓴다. 낯선 이름만 나열하기보다 ‘할아버지·손자·관객·우승자’처럼 상황에 필요한 역할·관계를 활용한다.
- 인물 이름 자체가 관심 포인트면 이름을 쓰되, 어떤 상황에서 누구와 무엇을 하는지 함께 드러낸다. 채널의 인물 표기 가이드를 우선한다.
- 장면에서 무엇을 보면 재미있는지 짚는다. 예상과 다른 행동, 숨은 사정, 표정, 대화의 엇갈림 중 가장 선명한 하나를 고른다.
- 궁금증을 남기거나 재미있는 반응을 먼저 알려주는 방식 모두 가능하다. 모든 제목을 ‘진짜 이유·정체’로 끝내지 않는다.
- 기간·금액·횟수는 사건을 이해하는 데 도움이 되고 영상에 근거가 있을 때만 활용한다.
- 영상에 없는 사건·동기·결과를 만들지 않는다. 추상적인 과장보다 실제 행동과 상황으로 흥미를 만든다.

[두 줄 구성]
- 처음부터 line1과 line2를 함께 작성한다. 기본 구조는 ‘상황·조건 → 핵심 행동·반응·인물’이다.
- 내용에 따라 ‘대상 → 의외의 특징’, ‘질문 → 답변’, ‘인상적인 대사’도 사용할 수 있다.
- 두 줄을 이어 읽으면 자연스러워야 한다. 의미 단위와 읽는 호흡을 기준으로 줄을 나눈다.
- 글자 수를 맞추려고 단어·이름·밀접한 구절을 어색하게 나누지 않는다. 두 줄 길이가 달라도 괜찮다.
- 길면 표현을 짧게 다시 쓴다. 공백 포함 총 24자 안팎을 목표로 하되 의미 단위를 우선한다.

[말투]
- 짧고 일상적인 한국어. ‘~하는 관객’, ‘~한 사람’, ‘~의 첫 업무’처럼 행동이나 대상을 선명하게 남긴다.
- ‘이유·방법·정체’는 영상에서 그 궁금증을 실제로 풀어줄 때만 사용한다.
- ㅋㅋ, 물음표, 느낌표는 장면 분위기에 맞을 때만 절제해 사용한다.
- 작품명·출처·해시태그·시청 유도 문구는 제목에 섞지 않는다.

[좋은 예시 — 구조와 줄바꿈의 참고이며 현재 영상의 사실로 사용하지 말 것]
1. 상황 → 예상과 다른 행동
{"line1":"투표함에 넣다 말고","line2":"표 도로 뺀 관객"}
하던 행동과 바뀐 행동을 연결해 궁금증을 만든다.
2. 상황 → 인물의 반응
{"line1":"샴페인 선물 받고","line2":"신난 원희 ㅋㅋ"}
짧은 상황 설명 뒤에 인물과 반응을 붙인다.
3. 행동 → 의외의 전개
{"line1":"한식 만들다가","line2":"실력 들통난 정지선 셰프"}
두 줄을 이어 읽으면 하나의 자연스러운 표현이 된다.
4. 대상 → 궁금한 특징
{"line1":"채정안 최애 구두의","line2":"치명적 단점"}
영상에서 실제로 그 단점을 보여줄 때 사용하는 구조다.
5. 질문 → 의외의 답변
{"line1":"프링글스 한 통 가능?","line2":"원희 : 3통 먹어요"}
실제 대화만으로 재미가 전달되면 설명을 덧붙이지 않는다.
6. 인상적인 대사
{"line1":"나 오빠랑","line2":"벚꽃 본 적 없는데?"}
대사 자체에 흥미가 있으면 활용한다. 줄 길이보다 자연스러운 호흡을 우선한다.
7. 역할·시간 → 숨겨온 감정 (꿀벌무비 참고)
{"line1":"우승자가 9년 만에","line2":"터트린 본심"}
작품을 몰라도 이해되는 역할과 구체적인 시간으로 궁금증을 만든다. 실제로 그 본심이 드러나는 영상에만 쓴다.
8. 익숙한 관계 → 예상 밖의 사실 (꿀벌무비 참고)
{"line1":"10년 키운 아들이","line2":"내 자식이 아니다"}
관계와 강한 사실을 연결한다. 반전의 무게는 실제 내용에서 가져오며, 기간·혈연관계를 지어내지 않는다.
9. 관계가 드러나는 상황 → 봐야 할 반응 (누나스픽 참고)
{"line1":"친누나 얘기할때","line2":"서강준 표정"}
무슨 상황에서 누구의 어떤 반응을 보면 재미있는지 짚는다. 표정만으로 확인되지 않은 속마음을 단정하지 않는다.
10. 진지한 말 → 주변과의 온도 차 (누나스픽 참고)
{"line1":"저는 진지한데","line2":"뭐가 웃기죠?"}
말하는 사람과 주변 반응의 엇갈림을 짧은 구어체로 전달한다. 실제 대사나 확인되는 상황에 근거한다.

[피해야 할 예시]
{"line1":"투표함에 넣다 말고 표","line2":"도로 뺀 관객"}
‘표 도로 뺀 관객’이라는 의미 단위를 끊었다.
{"line1":"모두가 경악한","line2":"충격적인 반전"}
구체적인 인물·행동·상황이 없어 어떤 영상에도 붙일 수 있다.

예시의 인물·사건·표현을 복사하지 말고 현재 영상에 맞는 구조를 선택하라.
[출력 연결]
전체 대본 JSON의 title 필드에 {"line1":"...","line2":"..."} 객체를 넣는다.
검수에서 제목을 수정할 때도 이 규칙을 적용하고, 적절한 기존 두 줄은 유지한다.
"""


_LEN_FREE = "- 글자 수를 맞추려고 단어·이름·밀접한 구절을 어색하게 나누지 않는다. 두 줄 길이가 달라도 괜찮다."
_LEN_TOTAL = "- 길면 표현을 짧게 다시 쓴다. 공백 포함 총 24자 안팎을 목표로 하되 의미 단위를 우선한다."


def title_prompt(title_fit: dict | None = None) -> str:
    """제목 프롬프트. title_fit({font, sizes} — 채널 템플릿의 제목 폰트·줄별 상한 크기)이 있으면 '총 24자 안팎' 대신
    **줄당 글자 수를 처음부터** 정해 준다(2026-09-21 사용자 결정 "폭 검사를 넣는 게 아니라 처음에 글자 수를 정해야").
    글자 수는 v3 와 같은 자(safe_zone.title_char_budget — 폰 안전 폭 880px · 글자 크기 고정). 없으면 종전과 바이트 동일."""
    if not title_fit or not title_fit.get("sizes"):
        return TITLE_PROMPT
    from app.v3.safe_zone import title_char_budget
    sizes = [int(x) for x in title_fit["sizes"]]
    a, b = title_char_budget(sizes[0]), title_char_budget(sizes[1] if len(sizes) > 1 else sizes[0])
    rule = (f"- **길이(필수 — 처음부터 이 안에서 구상한다)**: line1 은 공백을 뺀 글자 **{a}자 이내**, line2 는 **{b}자 이내**"
            f"(띄어쓰기는 줄당 1~2번). 제목 글자 크기는 고정이라 이보다 길면 폰 화면에서 잘린다. 다 쓴 뒤 자르지 말고, "
            f"조사·수식어·부연을 덜고 더 짧은 말을 골라 **짧게 쓴다** — 짧을수록 눈에 들어온다. "
            f"상황 설명을 다 담으려 하지 말고 가장 선명한 한 가지만 남긴다. 아래 예시 중 이보다 긴 줄은 구조만 참고한다.")
    free = "- 글자 수를 맞추려고 단어·이름·밀접한 구절을 어색하게 나누지 않는다. 각 줄이 위 상한 안이면 두 줄 길이가 달라도 괜찮다."
    assert _LEN_FREE in TITLE_PROMPT and _LEN_TOTAL in TITLE_PROMPT
    return TITLE_PROMPT.replace(_LEN_TOTAL, "").replace(_LEN_FREE, rule + "\n" + free)


def normalize_title(value):
    """Keep semantic line breaks in the existing downstream string contract."""
    if isinstance(value, dict):
        lines = [str(value.get(k) or "") for k in ("line1", "line2")]
    else:
        lines = str(value or "").splitlines()
    return "\n".join(" ".join(line.split()) for line in lines if line.strip())[:40]
